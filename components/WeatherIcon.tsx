export function WeatherIcon({ iconCode, size = 64, className = '' }: WeatherIconProps) {
  const pattern = dotPatterns[iconCode] || dotPatterns['01d'];
  const dotSize = size / 9;

  return (
    <svg
      width={size}
      height={size}
      viewBox={`0 0 ${size} ${size}`}
      className={className}
      aria-hidden="true"
      style={{ shapeRendering: 'crispEdges' }}
    >
      {pattern.map((row, y) =>
        row.map((dot, x) =>
          dot ? (
            <rect
              key={`${x}-${y}`}
              x={x * dotSize + dotSize * 0.15}
              y={y * dotSize + dotSize * 0.15}
              width={dotSize * 0.7}
              height={dotSize * 0.7}
              fill="#ff5252"
              rx={dotSize * 0.1}
            />
          ) : null
        )
      )}
    </svg>
  );
}