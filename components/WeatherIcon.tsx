const dotPatterns: Record<string, number[][]> = {
  '01d': sun16,
  '01n': moon16,
  '02d': sunCloud16,
  '02n': moonCloud16,
  '03d': cloud16,
  '03n': cloud16,
  '04d': overcast16,
  '04n': overcast16,
  '09d': rain16,
  '09n': rain16,
  '10d': sunRain16,
  '10n': moonRain16,
  '11d': storm16,
  '11n': storm16,
  '13d': snow16,
  '13n': snow16,
  '50d': mist16,
  '50n': mist16,
};

export function WeatherIcon({ iconCode, size = 64, className = '' }: WeatherIconProps) {
  const pattern = dotPatterns[iconCode] || dotPatterns['01d'];
  const dotStep = size / GRID_SIZE;
  const dotSize = dotStep * 0.76;
  const dotRadius = dotSize * 0.35; // clean rounded matrix pill/dot

  return (
    <svg
      width={size}
      height={size}
      viewBox={`0 0 ${size} ${size}`}
      className={className}
      aria-hidden="true"
      style={{ display: 'inline-block', verticalAlign: 'middle' }}
    >
      {pattern.map((row, y) =>
        row.map((dot, x) =>
          dot ? (
            <rect
              key={`${x}-${y}`}
              x={x * dotStep + (dotStep - dotSize) / 2}
              y={y * dotStep + (dotStep - dotSize) / 2}
              width={dotSize}
              height={dotSize}
              fill="#ff5252"
              rx={dotRadius}
            />
          ) : null
        )
      )}
    </svg>
  );
}